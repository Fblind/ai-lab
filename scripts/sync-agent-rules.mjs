#!/usr/bin/env node
/**
 * Project AGENTS.md (+ docs/engineering-standards.md) into the files other tools read
 * (CLAUDE.md, .cursorrules by default; see `sync` in kit.config.json).
 *
 *   node scripts/sync-agent-rules.mjs [--dry-run] [--check]
 *
 *  --dry-run  print what would be written, write nothing
 *  --check    exit 1 when an output is missing or out of date (for CI)
 *
 * Writes stay inside this repository. An existing output that this script did not
 * generate (no header) is copied to <name>.bak-<timestamp> before being replaced.
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { isInside, loadConfig, parseArgs, repoRoot, timestamp } from "./lib.mjs";

const HEADER = "<!-- Generated by scripts/sync-agent-rules.mjs from AGENTS.md. Edit AGENTS.md, not this file. -->\n\n";

let args;
try {
  args = parseArgs(process.argv.slice(2), { flags: ["dry-run", "check"] });
} catch (error) {
  console.error(`error: ${error.message}`);
  process.exit(2);
}
const dryRun = Boolean(args["dry-run"]);
const check = Boolean(args.check);

const { sync } = loadConfig();
const agentsPath = resolve(repoRoot, sync.source);
const standardsPath = resolve(repoRoot, sync.standards);

for (const p of [agentsPath, standardsPath, ...sync.outputs.map((o) => resolve(repoRoot, o))]) {
  if (!isInside(repoRoot, p)) {
    console.error(`error: ${p} is outside the repository`);
    process.exit(1);
  }
}
if (!existsSync(agentsPath)) {
  console.error(`error: missing ${relative(repoRoot, agentsPath)}`);
  process.exit(1);
}

const standardsNote = existsSync(standardsPath)
  ? `\n\nAlso follow \`${sync.standards}\`.\n`
  : "\n";
const content = HEADER + readFileSync(agentsPath, "utf8").trimEnd() + standardsNote;

let stale = 0;
for (const output of sync.outputs) {
  const path = resolve(repoRoot, output);
  const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (existing === content) {
    console.log(`ok ${output}`);
    continue;
  }
  stale++;
  if (check) {
    console.log(`out of date: ${output}`);
    continue;
  }
  if (existing !== null && !existing.startsWith("<!-- Generated by")) {
    const bak = `${path}.bak-${timestamp()}`;
    console.log(`${dryRun ? "[dry-run] would back up" : "backup"} ${output} -> ${relative(repoRoot, bak)}`);
    if (!dryRun) copyFileSync(path, bak);
  }
  console.log(`${dryRun ? "[dry-run] would write" : "wrote"} ${output}`);
  if (!dryRun) writeFileSync(path, content);
}

if (check && stale) {
  console.error(`${stale} output(s) out of date. Run: node scripts/sync-agent-rules.mjs`);
  process.exit(1);
}
console.log(dryRun ? "Dry run done." : "Done.");
